@Injectable()
export class ExploreService {
  getTrips(category?: string, scope?: string) {
    let trips = DUMMY_TRIPS;
    if (scope) {
      trips = trips.filter((t) => t.scope === scope);
    }
    if (category && category !== 'All') {
      trips = trips.filter((t) => t.category === category);
    }
    return trips;
  }

  getTripById(id: number) {
    const trip = DUMMY_TRIPS.find((t) => t.id === id);
    if (!trip) return null;
    return {
      ...trip,
      overview:
        'Experience the magic of this breathtaking destination with our curated travel plan. We take care of all the logistics so you can focus on making memories.',
      agency: {
        name: trip.creator,
        rating: trip.rating,
        description:
          'A top-rated verified host specializing in local immersive experiences.',
      },
      illustratedMap: '/illustrated-map.jpg',
      hotels: [
        { name: 'Luxury Mountain Resort', rating: 5, nights: 2 },
        { name: 'Heritage Homestay', rating: 4, nights: 1 },
      ],
      days: [
        {
          day: 1,
          title: 'Arrival & Welcome',
          description:
            'Arrive at the destination. Transfer to the hotel and rest. Evening local market tour.',
          lat: trip.lat,
          lng: trip.lng,
        },
        {
          day: 2,
          title: 'Sightseeing',
          description:
            'Full day sightseeing covering major attractions and viewpoints.',
          lat: trip.lat + 0.8,
          lng: trip.lng + 1.2,
        },
        {
          day: 3,
          title: 'Adventure & Departure',
          description:
            'Morning adventure activity. Afternoon transfer back to the airport/station.',
          lat: trip.lat - 0.5,
          lng: trip.lng + 0.9,
        },
      ],
    };
  }
}
